def _scramble(value: int) -> int:
    return value ^ ((value & 0x0F) << 4)


_SCRAMBLE_TABLE = bytes(_scramble(value) for value in range(256))


class KgmDecoder(Decoder):
    name = "酷狗音乐 KGM"
    extensions = frozenset({".kgm", ".kgma", ".vpr", ".kgm.flac", ".vpr.flac"})

    def __init__(self) -> None:
        self._pub_key: bytes | None = None
        self._pub_key_path: Path | None = None

    def _load_pub_key(self, opts: DecodeOptions) -> bytes:
        key_path = opts.kgm_key or asset_path("kugou_key.xz")
        if self._pub_key is not None and self._pub_key_path == key_path:
            return self._pub_key
        try:
            self._pub_key = lzma.decompress(key_path.read_bytes())
        except FileNotFoundError:
            raise FormatError(f"缺少酷狗公钥文件: {key_path}（可通过 --kgm-key 指定）") from None
        except lzma.LZMAError:
            raise FormatError(f"酷狗公钥文件损坏: {key_path}") from None
        self._pub_key_path = key_path
        return self._pub_key

    def decode_to(
        self,
        path: Path,
        out: BinaryIO,
        opts: DecodeOptions,
        progress=None,
    ) -> DecodeResult:
        if path.stat().st_size < HEADER_LEN + BLOCK:
            raise FormatError(f"{path.name}: 文件过短")
        with path.open("rb") as fp:
            header = fp.read(HEADER_LEN)
            magic = header[:16]
            if magic not in (KGM_MAGIC, VPR_MAGIC):
                raise FormatError(f"{path.name}: 不是 KGM/VPR 文件")
            audio_offset = int.from_bytes(header[0x10:0x14], "little")
            crypto_version = int.from_bytes(header[0x14:0x18], "little")
            if crypto_version == 5:
                raise UnsupportedError(f"{path.name}: KGG(v5) 需要客户端密钥库，暂不支持")
            if audio_offset < HEADER_LEN or audio_offset > path.stat().st_size:
                raise FormatError(f"{path.name}: KGM 音频偏移非法")

            pub_key = self._load_pub_key(opts)
            own_key = header[0x1C:0x2C] + b"\x00"
            fp.seek(audio_offset)
            audio_total = path.stat().st_size - audio_offset
            block_count = (audio_total + BLOCK - 1) // BLOCK
            if block_count > len(pub_key):
                raise FormatError(f"{path.name}: 公钥耗尽（文件过大或损坏）")

            first = fp.read(64)
            first_decoded = self._decrypt_chunk(first, 0, own_key, pub_key)
            container = sniff_container(first_decoded)
            out.write(first_decoded)
            position = 64
            remaining = audio_total - 64
            while remaining:
                chunk = fp.read(min(1024 * 1024, remaining))
                if not chunk:
                    break
                out.write(self._decrypt_chunk(chunk, position, own_key, pub_key))
                position += len(chunk)
                remaining -= len(chunk)
                if progress:
                    progress(position, audio_total, "decrypt")
        return DecodeResult(container=container, source=f"kgm-v{crypto_version}")

    @staticmethod
    def _decrypt_chunk(chunk: bytes, position: int, own_key: bytes, pub_key: bytes) -> bytes:
        """直接按字节推导，避免为 17 个相位构建百万级查表。"""
        out = bytearray(len(chunk))
        mend_len = len(MEND_TABLE)
        for index, value in enumerate(chunk):
            global_index = position + index
            packed = value ^ own_key[global_index % OWN_KEY_LEN]
            public_byte = pub_key[global_index // BLOCK]
            out[index] = (
                _SCRAMBLE_TABLE[packed]
                ^ _SCRAMBLE_TABLE[public_byte ^ MEND_TABLE[global_index % mend_len]]
            )
        return bytes(out)
